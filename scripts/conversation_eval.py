"""Phase 7B -- development-only conversation-quality evaluation against the REAL configured
OpenAI model (never a mock). Runs the scripted scenarios end to end through the actual call_ai
orchestration and prints full transcripts for manual rubric scoring; does not score itself
(quality judgment isn't something to automate here).

Never runs against production customer data -- every conversation_id is a fresh, synthetic
pytest-style id, and everything this script creates (CustomerProfileState, any
FragranceRecommendation + inventory snapshot generated by a real preview_ready) is deleted again
at the end unless --keep is passed.

Usage:
    python scripts/conversation_eval.py
    python scripts/conversation_eval.py --only A,D,J
    python scripts/conversation_eval.py --keep
"""

import argparse
import asyncio
import logging
import sys
import uuid

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from sqlalchemy import delete

from app.ai.conversation_flow import call_ai
from app.db.models import CustomerProfileState, FragranceRecommendation
from app.db.session import SessionLocal

SHOP_DOMAIN = "test-shop.myshopify.com"

SCENARIOS = {
    "A": {"name": "General greeting", "customer_name": "Sam", "turns": ["hey"]},
    "A2": {"name": "General greeting, name unknown (real Shopify edge case)", "customer_name": None, "turns": ["hey"]},
    "B": {"name": "Casual conversation", "customer_name": "Sam", "turns": ["long day honestly", "still working", "got a party friday though"]},
    "C": {"name": "Direct fragrance intent", "customer_name": "Sam", "turns": ["I need something fresh for my wedding"]},
    "D": {"name": "Strong dislike", "customer_name": "Sam", "turns": ["I hate that stinky oud smell"]},
    "E": {"name": "Layman", "customer_name": "Sam", "turns": ["I don't know perfume notes, I just want something clean"]},
    "F": {"name": "Existing preference", "customer_name": "Sam", "turns": ["I like fresh scents but they always disappear too fast"]},
    "G": {"name": "Strong occasion reveal", "customer_name": "Sam", "turns": ["I'm having this custom made for a formal work event"]},
    "H": {"name": "User changes mind", "customer_name": "Sam", "turns": [
        "I need something fresh and long lasting for a formal evening event, no oud",
        "actually maybe I want it a little sweeter",
    ]},
    "I": {"name": "General conversation, no fragrance signal yet", "customer_name": "Sam", "turns": ["hi there", "not much, just chilling", "yeah it's been a slow week"]},
    "J": {"name": "Very direct customer", "customer_name": "Sam", "turns": ["Make me a fresh, long-lasting, noticeable scent with no oud for an evening event."]},
}


def _conversation_id(label: str) -> str:
    return f"pytest-eval-{label}-{uuid.uuid4().hex[:8]}"


async def _run_scenario(label: str, spec: dict) -> dict:
    conversation_id = _conversation_id(label)
    history: list[dict] = []
    transcript: list[dict] = []

    async with SessionLocal() as session:
        for user_message in spec["turns"]:
            history.append({"role": "user", "content": user_message})
            result = await call_ai(session, history, conversation_id, f"{conversation_id}@example.test", spec["customer_name"], SHOP_DOMAIN)
            transcript.append({"role": "user", "content": user_message})
            transcript.append({"role": "assistant", "content": result["replyText"]})
            if result.get("sseEvents"):
                transcript.append({"role": "sse_events", "content": result["sseEvents"]})
            history = result.get("updatedMessages") or history

    return {"label": label, "name": spec["name"], "conversationId": conversation_id, "transcript": transcript}


async def _cleanup(conversation_id: str) -> None:
    async with SessionLocal() as session:
        await session.execute(delete(FragranceRecommendation).where(FragranceRecommendation.conversationId == conversation_id))
        await session.execute(delete(CustomerProfileState).where(CustomerProfileState.conversationId == conversation_id))
        await session.commit()


def _print_transcript(result: dict) -> None:
    print(f"\n{'=' * 70}\nScenario {result['label']} -- {result['name']} (conversation_id={result['conversationId']})\n{'=' * 70}")
    for turn in result["transcript"]:
        if turn["role"] == "sse_events":
            for event in turn["content"]:
                print(f"  [sse] {event.get('type')}: {({k: v for k, v in event.items() if k != 'type'})}")
        else:
            print(f"{turn['role']:>9}: {turn['content']}")


async def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", default=None, help="Comma-separated scenario labels, e.g. A,D,J")
    parser.add_argument("--keep", action="store_true", help="Leave created rows in place instead of deleting them.")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(message)s")

    labels = args.only.split(",") if args.only else list(SCENARIOS.keys())
    conversation_ids = []
    for label in labels:
        result = await _run_scenario(label, SCENARIOS[label])
        conversation_ids.append(result["conversationId"])
        try:
            _print_transcript(result)
        finally:
            # Clean up immediately, not batched at the end -- a crash mid-run (a bad console
            # encoding, a network blip) must never leave synthetic rows behind.
            if not args.keep:
                await _cleanup(result["conversationId"])

    if not args.keep:
        print(f"\nCleaned up {len(conversation_ids)} scenario(s).")
    else:
        print(f"\n--keep set -- left {len(conversation_ids)} scenario(s) in place: {conversation_ids}")

    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
